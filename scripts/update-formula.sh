#!/bin/sh
# Regenerates Formula/sys1.rb for the latest (or given) sys1 release, using
# the SHA-256 checksums GoReleaser publishes with every release.
#
#   scripts/update-formula.sh            # latest release
#   scripts/update-formula.sh v0.1.0     # a specific one
set -eu
REPO=A-Hackers-Guide/sys1
tag=${1:-}
if [ -z "$tag" ]; then
  tag=$(curl -fsSL "https://api.github.com/repos/$REPO/releases/latest" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)
fi
[ -n "$tag" ] || { echo "no release found" >&2; exit 1; }
v=${tag#v}
sums=$(curl -fsSL "https://github.com/$REPO/releases/download/$tag/checksums.txt")
sha() {
  s=$(printf '%s\n' "$sums" | awk -v f="sys1_${v}_$1.tar.gz" '$2 == f { print $1 }')
  [ -n "$s" ] || { echo "missing checksum for $1" >&2; exit 1; }
  printf '%s' "$s"
}
url="https://github.com/$REPO/releases/download/$tag/sys1_${v}"

cat > "$(dirname "$0")/../Formula/sys1.rb" <<RUBY
# This file is generated by scripts/update-formula.sh. Do not edit by hand.
class Sys1 < Formula
  desc "Pool the spare power of every computer into one cloud"
  homepage "https://a-hackers-guide.github.io/sys1/"
  version "$v"
  license "Unlicense"

  on_macos do
    on_arm do
      url "${url}_darwin_arm64.tar.gz"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "${url}_darwin_amd64.tar.gz"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      if Hardware::CPU.is_64_bit?
        url "${url}_linux_arm64.tar.gz"
        sha256 "$(sha linux_arm64)"
      else
        url "${url}_linux_armv7.tar.gz"
        sha256 "$(sha linux_armv7)"
      end
    end
    on_intel do
      url "${url}_linux_amd64.tar.gz"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "sys0", "sys1"
    doc.install "README.md", "CHANGELOG.md", "docs/GETTING-STARTED.md"
  end

  # \`brew services start sys1\` keeps a node running in the background.
  service do
    run [opt_bin/"sys1", "serve", "--no-open"]
    keep_alive true
    log_path var/"log/sys1.log"
    error_log_path var/"log/sys1.log"
  end

  def caveats
    <<~EOS
      Lend this machine to a pool:   sys0
      Run a node here:               sys1
      Keep a node running:           brew services start sys1
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sys0 version")
    assert_match version.to_s, shell_output("#{bin}/sys1 version")
    assert_match "sys1-join", shell_output("#{bin}/sys0 join nonsense 2>&1", 1)
  end
end
RUBY
echo "Formula/sys1.rb -> $tag"
